#!/usr/bin/env python3
"""Generate the Steamworks 1.42 flat-API shim (steam_api_flat_142.cpp).

RoR2's Facepunch.Steamworks binds to the SDK 1.42 flat API and requests 1.42 interface
versions (SteamUser019, ...). Current arm64 libsteam_api.dylib builds only ship a newer flat API,
whose wrappers assume newer vtable layouts. Each generated wrapper here calls the method on the
1.42 interface class, matching the interface object Steam returns for the old version string.

usage: gen_shim.py <sdk142 dir> <out.cpp>
"""
import collections
import json
import re
import sys

sdk, out = sys.argv[1], sys.argv[2]
api = json.load(open(sdk + "/steam_api.json"))
by_flat = {}
seen = collections.Counter()
for m in api["methods"]:
    base = "SteamAPI_%s_%s" % (m["classname"], m["methodname"])
    n = seen[base]; seen[base] += 1
    by_flat[base if n == 0 else base + str(n - 1)] = m

decl = re.compile(r"^S_API\s+(.+?)\s+(SteamAPI_(ISteam\w+?)_(\w+))\((.*)\);\s*$")
lines = ["// Generated by gen_shim.py from Steamworks SDK 1.42 steam_api_flat.h -- do not edit.",
         '#include "steam_api.h"', '#include "steam_gameserver.h"', '#include "isteamappticket.h"', "",
         '#define S_SHIM extern "C" __attribute__((visibility("default")))', ""]
count = skipped = 0
for raw in open(sdk + "/steam_api_flat.h"):
    m = decl.match(raw.strip())
    if not m:
        continue
    ret, flat, cls, _, params = m.groups()
    info = by_flat.get(flat)
    if info is None:
        skipped += 1
        continue
    plist = [p.strip() for p in params.split(",")] if params.strip() else []
    assert plist and plist[0].startswith("intptr_t"), flat
    args = []
    json_params = info.get("params", [])
    for i, p in enumerate(plist[1:]):
        name = re.findall(r"(\w+)\s*$", p)[0]
        jtype = json_params[i]["paramtype"] if i < len(json_params) else ""
        if "CSteamID" in jtype and "CSteamID" not in p:
            args.append("CSteamID((uint64)%s)" % name)
        elif "CGameID" in jtype and "CGameID" not in p:
            args.append("CGameID((uint64)%s)" % name)
        else:
            args.append(name)
    if info["methodname"] == "Destruct" + cls:  # flat wrapper for the virtual destructor
        call = "((%s*)instancePtr)->~%s()" % (cls, cls)
    else:
        call = "((%s*)instancePtr)->%s(%s)" % (cls, info["methodname"], ", ".join(args))
    jret = info.get("returntype", "")
    if ret == "void":
        body = call + ";"
    elif ("CSteamID" in jret or "CGameID" in jret) and "CSteamID" not in ret and "CGameID" not in ret:
        body = "return %s.ConvertToUint64();" % call
    else:
        body = "return (%s)%s;" % (ret, call)
    lines.append("S_SHIM %s %s(%s) { %s }" % (ret, flat, params, body))
    count += 1
open(out, "w").write("\n".join(lines) + "\n")
print("generated %d wrappers (%d declarations without API info skipped)" % (count, skipped))
